"""Eight original, text-free heraldic flags. Generated artwork is CC0; no external art."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import json, math, re
ROOT=Path(__file__).resolve().parents[2]
DESIGNS=[('solar_crown','Solar Crown','legendary','#602741','#FFCF58','crown'),
 ('aurora_wings','Aurora Wings','epic','#153C59','#70FFD8','wings'),
 ('inferno_crest','Inferno Crest','epic','#482135','#FF9A48','flame'),
 ('eclipse_order','Eclipse Order','legendary','#211C48','#DCB6FF','eclipse'),
 ('storm_sigil','Storm Sigil','epic','#16305B','#8EE9FF','bolt'),
 ('tidal_crest','Tidal Crest','epic','#123F60','#72F4D5','wave'),
 ('rose_diamond','Rose Diamond','epic','#45264D','#FFB8E7','diamond'),
 ('golden_vanguard','Golden Vanguard','legendary','#163D47','#FFE28A','shield')]
def polygon(draw,points,fill,stroke='#091A2E',width=12):
    draw.polygon(points,fill=fill);draw.line(points+[points[0]],fill=stroke,width=width,joint='curve')
def generate():
    out=ROOT/'assets/shop_flags/art';out.mkdir(parents=True,exist_ok=True)
    sheet=Image.new('RGB',(1200,480),'#081E30');sd=ImageDraw.Draw(sheet)
    for i,(key,name,rarity,bg,fg,kind) in enumerate(DESIGNS):
        im=Image.new('RGB',(768,512),bg);d=ImageDraw.Draw(im)
        # Broad alternating rays stay legible in the map motif and in a 36px nameplate.
        for n in range(0,12,2):
            a,b=n*math.pi/6,(n+1)*math.pi/6
            d.polygon([(384,256),(384+1000*math.cos(a),256+1000*math.sin(a)),(384+1000*math.cos(b),256+1000*math.sin(b))],fill=tuple(min(255,int(bg[j:j+2],16)+16) for j in (1,3,5)))
        d.ellipse((220,92,548,420),fill='#0C2035',outline=fg,width=12)
        if kind=='crown':
            polygon(d,[(230,180),(305,222),(384,126),(463,222),(538,180),(500,352),(268,352)],fg)
            d.rounded_rectangle((268,332,500,376),12,fill=fg,outline='#091A2E',width=10)
            polygon(d,[(384,220),(420,260),(384,310),(348,260)],'#FF925B',width=7)
        elif kind=='wings':
            for sign in (-1,1):
                polygon(d,[(384,220),(384+sign*208,132),(384+sign*164,260),(384+sign*85,322),(384,350)],fg)
            polygon(d,[(384,156),(438,257),(384,367),(330,257)],'#F0FFEF',width=10)
        elif kind=='flame':
            polygon(d,[(374,106),(446,222),(478,181),(512,290),(475,367),(384,394),(290,356),(266,275),(333,180),(325,280),(387,228)],fg)
            polygon(d,[(384,230),(432,316),(384,369),(340,320)],'#FFF1A8',width=8)
        elif kind=='eclipse':
            d.ellipse((275,147,493,365),fill=fg);d.ellipse((336,116,530,310),fill=bg)
            polygon(d,[(480,298),(496,330),(529,346),(496,362),(480,395),(464,362),(431,346),(464,330)],'#FFF2D2',width=7)
        elif kind=='bolt':
            polygon(d,[(398,100),(280,278),(365,278),(338,410),(496,215),(405,215),(451,100)],fg)
        elif kind=='wave':
            polygon(d,[(242,322),(285,250),(345,216),(404,225),(432,260),(398,276),(374,258),(346,278),(369,309),(433,302),(502,257),(522,326),(466,365),(350,378),(273,357)],fg)
        elif kind=='diamond':
            polygon(d,[(285,173),(483,173),(528,240),(384,397),(240,240)],fg)
            d.line([(240,240),(528,240)],fill='#091A2E',width=9);d.line([(330,174),(308,240),(384,397),(460,240),(438,174)],fill='#6C4482',width=9)
        else:
            polygon(d,[(256,158),(384,111),(512,158),(494,311),(452,363),(384,403),(316,363),(274,311)],fg)
            polygon(d,[(384,174),(447,280),(414,280),(414,339),(354,339),(354,280),(321,280)],'#197D88',width=9)
        im.save(out/(key+'.png'));tile=im.resize((282,188),Image.Resampling.LANCZOS)
        x,y=12+(i%4)*300,12+(i//4)*240;sheet.paste(tile,(x,y));sd.text((x,y+198),name,fill='#E5FAFF',font=ImageFont.truetype('C:/Windows/Fonts/arialbd.ttf',17))
    folder=ROOT/'assets/crests-v13';folder.mkdir(exist_ok=True);sheet.save(folder/'preview.png')
    (folder/'README.md').write_text('Original Atlas Reign flags, generated by tools/frontier/generate_crest_flags.py. Artwork dedicated to CC0 1.0. No third-party images, fonts or symbols are embedded in the flag files.\n',encoding='utf-8')
    source=ROOT/'assets/shop_flags/flags.json';data=json.loads(source.read_text(encoding='utf-8'))
    data['flags']=[f for f in data['flags'] if f['key'] not in {d[0] for d in DESIGNS}]
    for key,name,rarity,_,_,kind in DESIGNS:data['flags'].append(dict(key=key,name=name,rarity=rarity,theme='Crests',prompt='Original geometric '+kind+' emblem. Generated by tools/frontier/generate_crest_flags.py; CC0.'))
    source.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    manifest=ROOT/'src/shared/Assets/ShopFlags.luau';s=manifest.read_text(encoding='utf-8')
    for key,_,_,_,_,_ in DESIGNS:s=re.sub(r'^\s*\{ key = "'+key+r'".*\n','',s,flags=re.M)
    rows=''.join(f'\t\t{{ key = "{key}", name = "{name}", theme = "Crests", rarity = "{rarity}", atlas = 1, x = 0, y = 0, w = 768, h = 512, product = 0, staging = 0 }},\n' for key,name,rarity,_,_,_ in DESIGNS)
    s=s.replace('\tsets = {', '\tsets = {',1);at=s.index('\n\t},\n\tsets');s=s[:at]+'\n'+rows.rstrip('\n')+s[at:]
    manifest.write_text(s,encoding='utf-8',newline='\n')
    print('Generated eight CC0 crest flags; historical flag keys preserved.')
if __name__=='__main__':generate()
