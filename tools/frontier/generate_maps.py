"""Generate two original, rotationally symmetric Frontier maps and all eight terrain previews.

Requires numpy, Pillow and zstandard (also used by the upstream map importer). No downloaded art.
"""
from pathlib import Path
import base64
import re
import numpy as np
from PIL import Image
import zstandard

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'assets/frontier'
W,H=960,640
y,x=np.mgrid[0:H,0:W]
u,v=(x+.5)/W,(y+.5)/H


def generate(key, name, module):
    # Absolute coordinates preserve 180-degree symmetry, including every coastline perturbation.
    a,b=np.abs(u-.5),np.abs(v-.5)
    ripple=.025*np.cos(v*18*np.pi)*np.cos(u*12*np.pi)
    if key == 'twin_straits':
        land=((a/.43)**2+(b/.43)**2 < 1+ripple) & ((a > .055+.023*np.cos(v*6*np.pi)) | (b<.035))
        # Two narrow crossings and two sea approaches reward coordinated team attacks.
        land |= (a<.15) & (b>.24) & (b<.27)
    else:
        land=np.zeros((H,W),dtype=bool)
        for cx,cy,rx,ry in [(.25,.27,.18,.18),(.75,.73,.18,.18),(.75,.27,.18,.18),(.25,.73,.18,.18),(.5,.5,.09,.12)]:
            land |= ((u-cx)/rx)**2+((v-cy)/ry)**2 < 1+ripple
        land |= ((a-.38)**2+(b-.015)**2 < .035**2)
    assert np.array_equal(land,land[::-1,::-1]), 'Map must be rotationally symmetric'
    assert .3 < land.mean() < .75
    shore=np.zeros_like(land)
    shore[1:] |= land[1:] != land[:-1]; shore[:-1] |= land[1:] != land[:-1]
    shore[:,1:] |= land[:,1:] != land[:,:-1]; shore[:,:-1] |= land[:,1:] != land[:,:-1]
    elevation=np.where(np.cos(a*23)*np.cos(b*21)>.55,15,5).astype('uint8')
    tiles=np.where(land,128+elevation,40).astype('uint8') | (shore.astype('uint8')*64)
    # Farthest-point sampling gives the countries well-spaced, valid inland spawns.
    candidates=np.argwhere(land & ~shore)[::41]
    chosen=[]; distance=np.full(len(candidates),1e12)
    for _ in range(24):
        point=candidates[np.argmax(distance)]; chosen.append(point)
        distance=np.minimum(distance,((candidates-point)**2).sum(axis=1))
    blob=base64.b64encode(zstandard.ZstdCompressor(level=19).compress(tiles.tobytes())).decode()
    nations=',\n'.join(f'  {{name="{name} {i+1:02}", x={p[1]}, y={p[0]}}}' for i,p in enumerate(chosen))
    text=f'''-- Original Frontier map, generated by tools/frontier/generate_maps.py, 2026-10-31. CC0.
return {{
 id="{key}", name="{name}", width={W}, height={H}, k_lin=1,
 land_tiles={int(land.sum())}, size={W*H}, codec="zstd+base64",
 terrain="{blob}",
 nations={{
{nations}
 }}
}}
'''
    (ROOT/f'src/shared/Data/Maps/{module}.luau').write_text(text,encoding='utf-8',newline='\n')
    return int(land.sum())


def preview(p):
    text=p.read_text(); w=int(re.search(r'width\s*=\s*(\d+)',text)[1]); h=int(re.search(r'height\s*=\s*(\d+)',text)[1])
    key=re.search(r'id\s*=\s*"([^"]+)"',text)[1]
    blob=re.search(r'terrain\s*=\s*"([^"]+)"',text)[1]
    tiles=np.frombuffer(zstandard.ZstdDecompressor().decompress(base64.b64decode(blob)),dtype='uint8').reshape(h,w)
    land=(tiles&128)!=0; shore=(tiles&64)!=0; mag=tiles&31
    colors=np.zeros((h,w,4),dtype='uint8'); colors[:]=(32,75,98,255)
    colors[land]=(168,186,148,255); colors[land&(mag>=10)]=(182,172,147,255)
    colors[land&(mag>=20)]=(223,230,223,255);colors[land&shore]=(214,200,154,255)
    colors[land&(mag==31)]=(13,28,41,255)
    image=Image.fromarray(colors); image.thumbnail((512,342),Image.Resampling.LANCZOS)
    image.save(OUT/f'map_{key}.png')


if __name__ == '__main__':
    OUT.mkdir(exist_ok=True,parents=True)
    for key,name,module in [('twin_straits','Twin Straits','TwinStraits'),('iron_archipelago','Iron Archipelago','IronArchipelago')]:
        count=generate(key,name,module); print(key,count,'land tiles')
    for p in list((ROOT/'src/shared/Data/Maps').glob('*.luau'))+list((ROOT/'src/server/MapData').glob('*.luau')):
        preview(p)
